#!/usr/bin/env python3
"""Car A's lidar, a Velodyne VLP-16 Puck Hi-Res, as an Isaac Sim RTX lidar profile.

    python3 make_lidars.py OUT_DIR [--calibration VLP16_hires.yaml]

Run with any Python that has pxr (Isaac Sim's own venv does). It writes OUT_DIR/VLP16.usda,
an OmniLidar prim with 16 lasers at the elevations of Nebula's factory calibration for the
Hi-Res (nebula_decoders/calibration/velodyne/VLP16_hires.yaml, the file car A's driver
decodes with: -10 to +10 deg, 1.33 deg apart). It spins at 600 rpm (10 Hz, car A's
VLP16.param.yaml) with a single return, and ranges from 0.3 to 100 m.

It emits along the prim's +x with +z up, as every Isaac lidar does, which is also the
`vlp16` frame Nebula publishes in, so the rig needs no emitter rotation.

After the golf cart twin's make_lidars.py (NEWSLabNTU/2026-golf-cart,
src/simulation/golfcart_twin/isaac), whose VLP-32C timing findings this reuses. The
attribute set is NVIDIA's Example_Rotary.usda's (OmniSensorGenericLidarCoreAPI).
"""
import argparse
import math
import os

import yaml
from pxr import Sdf, Usd

NEBULA_VLP16_HIRES = "/opt/autoware/1.5.0/share/nebula_decoders/calibration/velodyne/VLP16_hires.yaml"

COMMON = {
    "omni:sensor:Core:accumulateOutputs": (Sdf.ValueTypeNames.Bool, True),
    "omni:sensor:Core:azimuthErrorMean": (Sdf.ValueTypeNames.Float, 0.0),
    "omni:sensor:Core:elevationErrorMean": (Sdf.ValueTypeNames.Float, 0.0),
    "omni:sensor:Core:intensityMappingType": (Sdf.ValueTypeNames.Token, "LINEAR"),
    "omni:sensor:Core:intensityProcessing": (Sdf.ValueTypeNames.Token, "NORMALIZATION"),
    "omni:sensor:Core:maxReturns": (Sdf.ValueTypeNames.UInt, 1),
    "omni:sensor:Core:minReflectance": (Sdf.ValueTypeNames.Float, 0.1),
    "omni:sensor:Core:pulseTimeNs": (Sdf.ValueTypeNames.UInt, 6),
    "omni:sensor:Core:rangeResolutionM": (Sdf.ValueTypeNames.Float, 0.004),
    "omni:sensor:Core:rayType": (Sdf.ValueTypeNames.Token, "IDEALIZED"),
    "omni:sensor:Core:rotationDirection": (Sdf.ValueTypeNames.Token, "CW"),
    "omni:sensor:Core:scanRateBaseHz": (Sdf.ValueTypeNames.UInt, 10),
    "omni:sensor:Core:skipDroppingInvalidPoints": (Sdf.ValueTypeNames.Bool, False),
    "omni:sensor:tickRate": (Sdf.ValueTypeNames.Float, 10.0),
}


def vlp16(path, calibration):
    lasers = sorted(yaml.safe_load(open(calibration))["lasers"], key=lambda l: l["laser_id"])
    if len(lasers) != 16:
        raise SystemExit(f"{calibration}: {len(lasers)} lasers, a VLP-16 has 16")
    n = len(lasers)
    elevation = [math.degrees(l["vert_correction"]) for l in lasers]
    azimuth = [math.degrees(l["rot_correction"]) for l in lasers]
    # The VLP-16 fires its 16 lasers one after another, 2.304 us apart, and repeats every
    # 55.296 us (18.08 kHz; Velodyne's VLP-16 manual): 1808 firings a revolution at 600 rpm,
    # 0.2 deg apart, at most 28,928 points. RTX's firing clock is patternFiringRateHz, which
    # must divide by the scan rate: 18080. (An earlier profile set reportRateBaseHz, which is
    # no RTX attribute: the firing clock stayed at its 36 kHz default, twice the VLP-16's, and
    # a firing spanning more than one 27.8 us tick rendered nothing, hence 1.5 us spacing.)
    fire = [i * 2304 for i in range(n)]
    zeros = [0.0] * n
    scalars = {
        "omni:sensor:Core:numberOfChannels": (Sdf.ValueTypeNames.UInt, n),
        "omni:sensor:Core:numberOfEmitters": (Sdf.ValueTypeNames.UInt, n),
        "omni:sensor:Core:patternFiringRateHz": (Sdf.ValueTypeNames.UInt, 18080),
        "omni:sensor:Core:scanType": (Sdf.ValueTypeNames.Token, "ROTARY"),
        "omni:sensor:Core:startAzimuthOffsetDeg": (Sdf.ValueTypeNames.Float, 0.0),
        "omni:sensor:Core:nearRangeM": (Sdf.ValueTypeNames.Float, 0.3),
        "omni:sensor:Core:farRangeM": (Sdf.ValueTypeNames.Float, 100.0),
        "omni:sensor:Core:rangeAccuracyM": (Sdf.ValueTypeNames.Float, 0.03),
        "omni:sensor:Core:azimuthErrorStd": (Sdf.ValueTypeNames.Float, 0.0),
        "omni:sensor:Core:elevationErrorStd": (Sdf.ValueTypeNames.Float, 0.0),
        "omni:sensor:Core:peakPowerW": (Sdf.ValueTypeNames.Float, 0.002),
    }
    F, U = Sdf.ValueTypeNames.FloatArray, Sdf.ValueTypeNames.UIntArray
    emitters = {
        "azimuthDeg": (F, azimuth), "elevationDeg": (F, elevation),
        "channelId": (U, list(range(1, n + 1))), "fireTimeNs": (U, fire),
        "distanceCorrectionM": (F, zeros), "emitterPeakPowerW": (F, zeros),
        "focalDistM": (F, zeros), "focalSlope": (F, zeros),
        "horOffsetM": (F, zeros), "vertOffsetM": (F, zeros),
    }
    if os.path.exists(path):
        os.remove(path)
    stage = Usd.Stage.CreateNew(path)
    stage.GetRootLayer().documentation = "Generated by autosdv_twin/isaac/make_lidars.py: do not edit"
    prim = stage.DefinePrim("/VLP16", "OmniLidar")
    stage.SetDefaultPrim(prim)
    prim.AddAppliedSchema("OmniSensorGenericLidarCoreAPI")
    for attr, (t, v) in {**COMMON, **scalars}.items():
        prim.CreateAttribute(attr, t).Set(v)
    for field, (t, v) in emitters.items():
        prim.CreateAttribute(f"omni:sensor:Core:emitterState:s001:{field}", t).Set(v)
    prim.CreateAttribute("omni:sensor:modelName", Sdf.ValueTypeNames.String).Set("VLP16")
    stage.GetRootLayer().Save()
    return n


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("out_dir")
    ap.add_argument("--calibration", default=NEBULA_VLP16_HIRES)
    a = ap.parse_args()
    os.makedirs(a.out_dir, exist_ok=True)
    n = vlp16(os.path.join(a.out_dir, "VLP16.usda"), a.calibration)
    print(f"VLP16.usda: {n} lasers")


if __name__ == "__main__":
    main()
